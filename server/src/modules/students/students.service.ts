import mongoose from "mongoose";
import AppError from "../../errors/AppError.js";
import type { IStudent, IGuardian } from "./students.interface.js";
import { Student } from "./students.model.js";
import { StudentCounter } from "./student-counter.model.js";
import { uploadMedia, deleteMedia } from "../media/index.js";

const MAX_FILE_SIZE = 5 * 1024 * 1024;

const ALLOWED_IMAGE_TYPES = ["image/jpeg", "image/png", "image/webp"];

type StudentPayload = Omit<IStudent, "studentId">;
type StudentUpdatePayload = Partial<IStudent>;

type MediaReference = {
  url: string;
  publicId: string;
};

type GuardianPayload = IGuardian & {
  _id?: string;
};

const generateStudentId = async (admissionDate: Date): Promise<string> => {
  const year = admissionDate.getFullYear();

  const counter = await StudentCounter.findOneAndUpdate(
    { _id: `student-${year}` },
    { $inc: { sequence: 1 } },
    {
      new: true,
      upsert: true,
      returnDocument: "after",
      includeResultMetadata: false,
    },
  );

  if (!counter) {
    throw new AppError(500, "Failed to generate student ID.");
  }

  const updatedCounter = counter as unknown as {
    sequence: number;
  };

  return `EDU-${year}-${String(updatedCounter.sequence).padStart(4, "0")}`;
};

const uploadImage = async (
  file: Express.Multer.File,
  folder: string,
): Promise<MediaReference> => {
  const uploaded = await uploadMedia(file, {
    folder,
    resourceType: "image",
    allowedMimeTypes: ALLOWED_IMAGE_TYPES,
    maxFileSizeBytes: MAX_FILE_SIZE,
  });

  return {
    url: uploaded.url,
    publicId: uploaded.publicId,
  };
};

const cleanupUploadedMedia = async (publicIds: string[]): Promise<void> => {
  await Promise.allSettled(
    publicIds.map((publicId) => deleteMedia(publicId, "image")),
  );
};

/**
 * Media processing is independent of ordinary student/guardian data.
 *
 * Supported multipart fields:
 *   photo
 *   guardianPhoto_0
 *   guardianPhoto_1
 *   ...
 */
const processStudentMedia = async (
  files: Express.Multer.File[],
  guardianCount: number,
): Promise<{
  studentPhoto?: MediaReference;
  guardianPhotos: Map<number, MediaReference>;
  uploadedPublicIds: string[];
}> => {
  const studentFiles: Express.Multer.File[] = [];
  const guardianFiles = new Map<number, Express.Multer.File>();

  for (const file of files) {
    if (file.fieldname === "photo") {
      if (studentFiles.length > 0) {
        throw new AppError(400, "Only one student photo is allowed.");
      }

      studentFiles.push(file);
      continue;
    }

    const match = /^guardianPhoto_(\d+)$/.exec(file.fieldname);

    if (!match) {
      throw new AppError(400, `Unsupported upload field: ${file.fieldname}`);
    }

    const index = Number(match[1]);

    if (!Number.isSafeInteger(index) || index < 0 || index >= guardianCount) {
      throw new AppError(
        400,
        `Invalid guardian photo field: ${file.fieldname}`,
      );
    }

    if (guardianFiles.has(index)) {
      throw new AppError(
        400,
        `Duplicate guardian photo field: ${file.fieldname}`,
      );
    }

    guardianFiles.set(index, file);
  }

  const uploadedPublicIds: string[] = [];
  let studentPhoto: MediaReference | undefined;
  const guardianPhotos = new Map<number, MediaReference>();

  try {
    // The entire media operation is conditional.
    if (files.length > 0) {
      if (studentFiles[0]) {
        studentPhoto = await uploadImage(studentFiles[0], "educore/students");
        uploadedPublicIds.push(studentPhoto.publicId);
      }

      for (const [index, file] of guardianFiles) {
        const reference = await uploadImage(file, "educore/guardians");

        guardianPhotos.set(index, reference);
        uploadedPublicIds.push(reference.publicId);
      }
    }

    return {
      guardianPhotos,
      uploadedPublicIds,
      ...(studentPhoto ? { studentPhoto } : {}),
    };
  } catch (error) {
    await cleanupUploadedMedia(uploadedPublicIds);
    throw error;
  }
};

/**
 * Admission: process ordinary data, process optional media,
 * then combine both when creating the record.
 */
const createStudentService = async (
  input: StudentPayload,
  files: Express.Multer.File[] = [],
) => {
  const payload = { ...input } as Record<string, unknown>;

  // Media references must be generated by the server, not supplied by JSON.
  delete payload.photo;

  const guardians = Array.isArray(payload.guardians)
    ? (payload.guardians as GuardianPayload[]).map((guardian) => {
        const { photo: _untrustedPhoto, ...data } = guardian;
        return data;
      })
    : [];

  payload.guardians = guardians;

  const media = await processStudentMedia(files, guardians.length);

  const session = await mongoose.startSession();

  try {
    let createdStudent: InstanceType<typeof Student> | null = null;

    await session.withTransaction(async () => {
      const admissionDate = new Date(payload.admissionDate as string | Date);

      if (Number.isNaN(admissionDate.getTime())) {
        throw new AppError(400, "Invalid admission date.");
      }

      // Attach generated references only when building the database payload.
      const persistencePayload: Record<string, unknown> = {
        ...payload,
        admissionDate,
      };

      if (media.studentPhoto) {
        persistencePayload.photo = media.studentPhoto;
      }

      persistencePayload.guardians = guardians.map((guardian, index) => ({
        ...guardian,
        ...(media.guardianPhotos.has(index)
          ? { photo: media.guardianPhotos.get(index) }
          : {}),
      }));

      const studentId = await generateStudentId(admissionDate);

      const [student] = await Student.create(
        [
          {
            ...persistencePayload,
            studentId,
          },
        ],
        { session },
      );

      if (!student) {
        throw new AppError(500, "Failed to create student.");
      }

      createdStudent = student;
    });

    return createdStudent;
  } catch (error) {
    await cleanupUploadedMedia(media.uploadedPublicIds);
    throw error;
  } finally {
    await session.endSession();
  }
};

const getAllStudentsService = async () => {
  return Student.find().sort({ createdAt: -1 });
};

const getStudentByIdService = async (id: string) => {
  if (!mongoose.isValidObjectId(id)) {
    throw new AppError(400, "Invalid student ID.");
  }

  const student = await Student.findById(id);

  if (!student) {
    throw new AppError(404, "Student not found.");
  }

  return student;
};

/**
 * Update ordinary fields independently from media.
 * Existing photos are preserved when their replacement files are absent.
 */
const updateStudentService = async (
  id: string,
  input: StudentUpdatePayload,
  files: Express.Multer.File[] = [],
) => {
  if (!mongoose.isValidObjectId(id)) {
    throw new AppError(400, "Invalid student ID.");
  }

  const student = await Student.findById(id);

  if (!student) {
    throw new AppError(404, "Student not found.");
  }

  const payload = { ...input } as Record<string, unknown>;

  // Never accept photo references directly from the client.
  delete payload.photo;

  const incomingGuardians = Array.isArray(payload.guardians)
    ? (payload.guardians as GuardianPayload[]).map((guardian) => {
        const { photo: _untrustedPhoto, ...data } = guardian;
        return data;
      })
    : undefined;

  if (incomingGuardians) {
    payload.guardians = incomingGuardians;
  }

  const updatedAdmissionType = input.admissionType ?? student.admissionType;

  const updatedTCDetails =
    input.tcDetails !== undefined ? input.tcDetails : student.tcDetails;

  if (updatedAdmissionType === "tc" && !updatedTCDetails) {
    throw new AppError(400, "TC details are required for TC admission.");
  }

  if (updatedAdmissionType === "regular" && updatedTCDetails) {
    throw new AppError(400, "TC details are only allowed for TC admission.");
  }

  // Validate the submitted guardian identity mapping before uploads.
  if (incomingGuardians) {
    for (const guardian of incomingGuardians as GuardianPayload[]) {
      if (!guardian._id) {
        continue;
      }

      const existingGuardian = student.guardians.find(
        (item) => item._id.toString() === guardian._id,
      );

      if (!existingGuardian) {
        throw new AppError(
          400,
          "A submitted guardian does not belong to this student.",
        );
      }
    }
  }

  const media = await processStudentMedia(
    files,
    incomingGuardians?.length ?? student.guardians.length,
  );

  try {
    const oldStudentPhoto = student.photo;
    const existingGuardians = student.guardians.map((guardian) => ({
      _id: guardian._id.toString(),
      photo: guardian.photo,
    }));

    const oldGuardianPublicIdsToDelete: string[] = [];

    // Ordinary data update.
    Object.assign(student, payload);

    // Replace the student photo only when a new one was uploaded.
    if (media.studentPhoto) {
      student.photo = media.studentPhoto;
    }

    // Only replace guardian photos when their corresponding files exist.
    if (incomingGuardians) {
      student.guardians = incomingGuardians.map((guardian, index) => {
        const existingGuardian = guardian._id
          ? existingGuardians.find(
              (item) => item._id.toString() === guardian._id,
            )
          : existingGuardians[index];

        const replacementPhoto = media.guardianPhotos.get(index);
        if (
          replacementPhoto &&
          existingGuardian?.photo?.publicId &&
          existingGuardian.photo.publicId !== replacementPhoto.publicId
        ) {
          oldGuardianPublicIdsToDelete.push(existingGuardian.photo.publicId);
        }

        return {
          ...guardian,
          ...(replacementPhoto
            ? { photo: replacementPhoto }
            : existingGuardian?.photo
              ? { photo: existingGuardian.photo }
              : {}),
        } as IGuardian;
      });
    }

    await student.save();

    const oldPublicIdsToDelete = new Set<string>(oldGuardianPublicIdsToDelete);

    if (
      media.studentPhoto &&
      oldStudentPhoto?.publicId &&
      oldStudentPhoto.publicId !== media.studentPhoto.publicId
    ) {
      oldPublicIdsToDelete.add(oldStudentPhoto.publicId);
    }

    for (const publicId of oldPublicIdsToDelete) {
      try {
        await deleteMedia(publicId);
      } catch (error) {
        console.error(
          `Failed to delete replaced Cloudinary asset "${publicId}":`,
          error,
        );
      }
    }

    return student;
  } catch (error) {
    await cleanupUploadedMedia(media.uploadedPublicIds);
    throw error;
  }
};

export const StudentsService = {
  createStudentService,
  getAllStudentsService,
  getStudentByIdService,
  updateStudentService,
};
