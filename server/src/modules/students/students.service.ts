const getAllStudentsService = async () => {
  return Student.find({ isDeleted: { $ne: true } }).sort({ createdAt: -1 });
};

const getStudentByIdService = async (id: string, includeDeleted = false) => {
  if (!mongoose.isValidObjectId(id)) {
    throw new AppError(400, "Invalid student ID.");
  }

  const filter: Record<string, unknown> = { _id: id };

  if (!includeDeleted) {
    filter.isDeleted = { $ne: true };
  }

  const student = await Student.findOne(filter);

  if (!student) {
    throw new AppError(404, "Student not found.");
  }

  return student;
};

/**
 * Update ordinary fields independently from media.
 * Existing photos are preserved when their replacement files are absent.
 */
const updateStudentService = async (
  id: string,
  input: StudentUpdatePayload,
  files: Express.Multer.File[] = [],
) => {
  if (!mongoose.isValidObjectId(id)) {
    throw new AppError(400, "Invalid student ID.");
  }

  const student = await Student.findById(id);

  if (!student) {
    throw new AppError(404, "Student not found.");
  }

  const payload = { ...input } as Record<string, unknown>;

  // Extract subject selection before removing non-student fields.
  const subjectSelection = payload.subjectSelection as
    | {
        configurationId: string;
        mainSubjectId: string;
        mainSubjectIds?: string[];
        fourthSubjectId: string;
      }
    | undefined;

  delete payload.subjectSelection;

  // Never accept academic history or photo references directly
  // from the client.
  delete payload.academicHistory;
  delete payload.photo;

  // Prepare guardian data without accepting client-supplied photos.
  const incomingGuardians = Array.isArray(payload.guardians)
    ? (payload.guardians as GuardianPayload[]).map((guardian) => {
        const { photo: _untrustedPhoto, ...data } = guardian;
        return data;
      })
    : undefined;

  if (incomingGuardians) {
    payload.guardians = incomingGuardians;
  }

  const updatedAdmissionType = input.admissionType ?? student.admissionType;

  const updatedTCDetails =
    input.tcDetails !== undefined ? input.tcDetails : student.tcDetails;

  if (updatedAdmissionType === "tc" && !updatedTCDetails) {
    throw new AppError(400, "TC details are required for TC admission.");
  }

  if (updatedAdmissionType === "regular" && updatedTCDetails) {
    throw new AppError(400, "TC details are only allowed for TC admission.");
  }

  // Validate guardian identity mapping before uploads.
  if (incomingGuardians) {
    for (const guardian of incomingGuardians) {
      if (!guardian._id) {
        continue;
      }

      const existingGuardian = student.guardians.find(
        (item) => item._id.toString() === guardian._id,
      );

      if (!existingGuardian) {
        throw new AppError(
          400,
          "A submitted guardian does not belong to this student.",
        );
      }
    }
  }

  // --------------------------------------------------
  // SUBJECT SELECTION
  // --------------------------------------------------

  let resolvedSubjects: IStudentSubjectSelection[] | undefined;
  if (subjectSelection) {
    const { configurationId, mainSubjectId, mainSubjectIds, fourthSubjectId } =
      subjectSelection;

    if (
      !mongoose.isValidObjectId(configurationId) ||
      !mongoose.isValidObjectId(fourthSubjectId)
    ) {
      throw new AppError(400, "Invalid subject selection IDs.");
    }

    const configuration = await SubjectConfiguration.findOne({
      _id: configurationId,
      isDeleted: false,
    });

    if (!configuration) {
      throw new AppError(404, "Subject configuration not found.");
    }

    // Validate configuration against the student's updated session/group.
    const updatedSession =
      typeof payload.academicSession === "string"
        ? payload.academicSession
        : student.academicSession;

    const updatedGroup =
      typeof payload.group === "string" ? payload.group : student.group;

    if (configuration.academicSession !== updatedSession) {
      throw new AppError(
        400,
        "Subject configuration does not match the academic session.",
      );
    }

    if (
      (configuration.group || "").trim().toUpperCase() !==
      (updatedGroup || "").trim().toUpperCase()
    ) {
      throw new AppError(
        400,
        "Subject configuration does not match the student's group.",
      );
    }

    const isHumanities = updatedGroup?.trim().toUpperCase() === "HUMANITIES";

    // Humanities uses three main subject IDs.
    // Science and Business Studies retain their existing single ID.
    const selectedMainSubjectIds = isHumanities
      ? (mainSubjectIds ?? [])
      : mainSubjectId
        ? [mainSubjectId]
        : [];

    // Validate the selected main subject IDs.
    if (
      selectedMainSubjectIds.length !== (isHumanities ? 3 : 1) ||
      selectedMainSubjectIds.some((id) => !mongoose.isValidObjectId(id)) ||
      new Set(selectedMainSubjectIds).size !== selectedMainSubjectIds.length
    ) {
      throw new AppError(400, "Invalid main subject selection.");
    }

    if (selectedMainSubjectIds.includes(fourthSubjectId)) {
      throw new AppError(
        400,
        "Main subjects and fourth subject must be different.",
      );
    }

    // Find all selected main subjects in the configuration.
    const mainConfiguredSubjects = configuration.subjects.filter((item) =>
      selectedMainSubjectIds.includes(item.subject.toString()),
    );

    const fourthConfiguredSubject = configuration.subjects.find(
      (item) => item.subject.toString() === fourthSubjectId,
    );

    if (
      mainConfiguredSubjects.length !== selectedMainSubjectIds.length ||
      mainConfiguredSubjects.some((item) => !item.isMainSubjectEligible)
    ) {
      throw new AppError(
        400,
        "One or more selected main subjects are not eligible.",
      );
    }

    // Humanities must select exactly one subject from each cluster.
    if (isHumanities) {
      const requiredClusters = [
        "HUMANITIES_CLUSTER_1",
        "HUMANITIES_CLUSTER_2",
        "HUMANITIES_CLUSTER_3",
      ];

      for (const cluster of requiredClusters) {
        const selectedFromCluster = mainConfiguredSubjects.filter(
          (item) => item.selectionGroup === cluster,
        );

        if (selectedFromCluster.length !== 1) {
          throw new AppError(
            400,
            `Select exactly one subject from ${cluster}.`,
          );
        }
      }
    }

    if (!fourthConfiguredSubject?.isFourthSubjectEligible) {
      throw new AppError(400, "The selected fourth subject is not eligible.");
    }

    // Include compulsory, group-mandatory, required-selection,
    // all selected main subjects, and the fourth subject.
    const configuredSubjects = configuration.subjects.filter(
      (item) =>
        ["COMPULSORY", "GROUP_MANDATORY", "REQUIRED_SELECTION"].includes(
          item.subjectType,
        ) ||
        selectedMainSubjectIds.includes(item.subject.toString()) ||
        item.subject.toString() === fourthSubjectId,
    );

    // Remove duplicate subject IDs while preserving configuration order.
    const uniqueConfiguredSubjects = [
      ...new Map(
        configuredSubjects.map((item) => [item.subject.toString(), item]),
      ).values(),
    ];

    const subjectIds = uniqueConfiguredSubjects.map((item) => item.subject);

    // Fetch actual subject documents.
    const subjectDocuments = await Subject.find({
      _id: { $in: subjectIds },
      status: "active",
      isDeleted: false,
    });

    if (subjectDocuments.length !== subjectIds.length) {
      throw new AppError(
        400,
        "One or more configured subjects are missing or inactive.",
      );
    }

    // Index subject documents by their MongoDB IDs.
    const subjectMap = new Map(
      subjectDocuments.map((subject) => [subject._id.toString(), subject]),
    );

    // Build the complete student subject-selection objects.
    resolvedSubjects = uniqueConfiguredSubjects.map((configuredSubject) => {
      const subjectId = configuredSubject.subject.toString();
      const subjectDocument = subjectMap.get(subjectId);

      if (!subjectDocument) {
        throw new AppError(400, "Configured subject could not be resolved.");
      }

      const isMainSubject = selectedMainSubjectIds.includes(subjectId);

      const isFourthSubject = subjectId === fourthSubjectId;

      return {
        subject: subjectDocument._id,
        subjectName: subjectDocument.name,
        subjectCode: subjectDocument.code,
        isElective: isMainSubject || isFourthSubject,
        isFourthSubject,
      };
    });
  }

  const media = await processStudentMedia(
    files,
    incomingGuardians?.length ?? student.guardians.length,
  );

  try {
    const oldStudentPhoto = student.photo;

    const existingGuardians = student.guardians.map((guardian) => ({
      _id: guardian._id.toString(),
      photo: guardian.photo,
    }));

    const oldGuardianPublicIdsToDelete: string[] = [];

    // Apply ordinary student data first.
    Object.assign(student, payload);

    // --------------------------------------------------
    // UPDATE ACADEMIC HISTORY
    // --------------------------------------------------

    if (resolvedSubjects) {
      let currentAcademicEntry = student.academicHistory.find(
        (entry) =>
          entry.academicSession === student.academicSession &&
          entry.className === student.className &&
          entry.group === student.group,
      );

      // Create an entry only if the matching entry does not exist.
      if (!currentAcademicEntry) {
        student.academicHistory.push({
          academicSession: student.academicSession,
          className: student.className,
          academicState: "current",
          subjects: resolvedSubjects,
          ...(student.group !== undefined ? { group: student.group } : {}),
          ...(student.section !== undefined
            ? { section: student.section }
            : {}),
          ...(student.rollNumber !== undefined
            ? { rollNumber: student.rollNumber }
            : {}),
        });
      } else {
        // Existing entry: replace its subjects.
        currentAcademicEntry.subjects = resolvedSubjects;
      }
    }

    // Replace student photo only when a new one was uploaded.
    if (media.studentPhoto) {
      student.photo = media.studentPhoto;
    }

    // Update guardians and preserve existing photos.
    if (incomingGuardians) {
      student.guardians = incomingGuardians.map((guardian, index) => {
        const existingGuardian = guardian._id
          ? existingGuardians.find((item) => item._id === guardian._id)
          : existingGuardians[index];

        const replacementPhoto = media.guardianPhotos.get(index);

        if (
          replacementPhoto &&
          existingGuardian?.photo?.publicId &&
          existingGuardian.photo.publicId !== replacementPhoto.publicId
        ) {
          oldGuardianPublicIdsToDelete.push(existingGuardian.photo.publicId);
        }

        return {
          ...guardian,
          ...(replacementPhoto
            ? { photo: replacementPhoto }
            : existingGuardian?.photo
              ? { photo: existingGuardian.photo }
              : {}),
        } as IGuardian;
      });
    }

    // Save student.
    await student.save();

    // --------------------------------------------------
    // CLEAN UP REPLACED CLOUDINARY ASSETS
    // --------------------------------------------------

    const oldPublicIdsToDelete = new Set<string>(oldGuardianPublicIdsToDelete);

    if (
      media.studentPhoto &&
      oldStudentPhoto?.publicId &&
      oldStudentPhoto.publicId !== media.studentPhoto.publicId
    ) {
      oldPublicIdsToDelete.add(oldStudentPhoto.publicId);
    }

    for (const publicId of oldPublicIdsToDelete) {
      try {
        await deleteMedia(publicId);
      } catch (error) {
        console.error(
          `Failed to delete replaced Cloudinary asset "${publicId}":`,
          error,
        );
      }
    }

    return student;
  } catch (error) {
    await cleanupUploadedMedia(media.uploadedPublicIds);
    throw error;
  }
};

const softDeleteStudentService = async (
  id: string,
  deletedBy: string,
  deletionReason?: string,
) => {
  if (!mongoose.isValidObjectId(id)) {
    throw new AppError(400, "Invalid student ID.");
  }

  const student = await Student.findOneAndUpdate(
    { _id: id, isDeleted: { $ne: true } },
    {
      $set: {
        isDeleted: true,
        deletedAt: new Date(),
        deletedBy,
        ...(deletionReason ? { deletionReason } : {}),
      },
    },
    { new: true, runValidators: true },
  );

  if (!student) {
    throw new AppError(404, "Student not found.");
  }

  return student;
};

const restoreStudentService = async (id: string, restoredBy: string) => {
  if (!mongoose.isValidObjectId(id)) {
    throw new AppError(400, "Invalid student ID.");
  }

  const student = await Student.findOneAndUpdate(
    { _id: id, isDeleted: true },
    {
      $set: {
        isDeleted: false,
        restoredAt: new Date(),
        restoredBy,
      },
      $unset: {
        deletedAt: 1,
        deletedBy: 1,
        deletionReason: 1,
      },
    },
    { returnDocument: "after", runValidators: true },
  );

  if (!student) {
    throw new AppError(404, "Deleted student not found.");
  }

  return student;
};

const getDeletedStudentsService = async () => {
  const deleted = await Student.find({ isDeleted: true }).sort({
    deletedAt: -1,
  });
  return deleted;
};

