const MAX_FILE_SIZE = 5 * 1024 * 1024;

const ALLOWED_IMAGE_TYPES = ["image/jpeg", "image/png", "image/webp"];

type StudentPayload = Omit<IStudent, "studentId">;
type StudentUpdatePayload = Partial<IStudent>;

type MediaReference = {
  url: string;
  publicId: string;
};

type GuardianPayload = IGuardian & {
  _id?: string;
};

const generateStudentId = async (admissionDate: Date): Promise<string> => {
  const year = admissionDate.getFullYear();

  const counter = await StudentCounter.findOneAndUpdate(
    { _id: `student-${year}` },
    { $inc: { sequence: 1 } },
    {
      new: true,
      upsert: true,
      returnDocument: "after",
      includeResultMetadata: false,
    },
  );

  if (!counter) {
    throw new AppError(500, "Failed to generate student ID.");
  }

  const updatedCounter = counter as unknown as {
    sequence: number;
  };

  return `EDU-${year}-${String(updatedCounter.sequence).padStart(4, "0")}`;
};

const uploadImage = async (
  file: Express.Multer.File,
  folder: string,
): Promise<MediaReference> => {
  const uploaded = await uploadMedia(file, {
    folder,
    resourceType: "image",
    allowedMimeTypes: ALLOWED_IMAGE_TYPES,
    maxFileSizeBytes: MAX_FILE_SIZE,
  });

  return {
    url: uploaded.url,
    publicId: uploaded.publicId,
  };
};

const cleanupUploadedMedia = async (publicIds: string[]): Promise<void> => {
  await Promise.allSettled(
    publicIds.map((publicId) => deleteMedia(publicId, "image")),
  );
};

/**
 * Media processing is independent of ordinary student/guardian data.
 *
 * Supported multipart fields:
 *   photo
 *   guardianPhoto_0
 *   guardianPhoto_1
 *   ...
 */
const processStudentMedia = async (
  files: Express.Multer.File[],
  guardianCount: number,
): Promise<{
  studentPhoto?: MediaReference;
  guardianPhotos: Map<number, MediaReference>;
  uploadedPublicIds: string[];
}> => {
  const studentFiles: Express.Multer.File[] = [];
  const guardianFiles = new Map<number, Express.Multer.File>();

  for (const file of files) {
    if (file.fieldname === "photo") {
      if (studentFiles.length > 0) {
        throw new AppError(400, "Only one student photo is allowed.");
      }

      studentFiles.push(file);
      continue;
    }

    const match = /^guardianPhoto_(\d+)$/.exec(file.fieldname);

    if (!match) {
      throw new AppError(400, `Unsupported upload field: ${file.fieldname}`);
    }

    const index = Number(match[1]);

    if (!Number.isSafeInteger(index) || index < 0 || index >= guardianCount) {
      throw new AppError(
        400,
        `Invalid guardian photo field: ${file.fieldname}`,
      );
    }

    if (guardianFiles.has(index)) {
      throw new AppError(
        400,
        `Duplicate guardian photo field: ${file.fieldname}`,
      );
    }

    guardianFiles.set(index, file);
  }

  const uploadedPublicIds: string[] = [];
  let studentPhoto: MediaReference | undefined;
  const guardianPhotos = new Map<number, MediaReference>();

  try {
    // The entire media operation is conditional.
    if (files.length > 0) {
      if (studentFiles[0]) {
        studentPhoto = await uploadImage(studentFiles[0], "educore/students");
        uploadedPublicIds.push(studentPhoto.publicId);
      }

      for (const [index, file] of guardianFiles) {
        const reference = await uploadImage(file, "educore/guardians");

        guardianPhotos.set(index, reference);
        uploadedPublicIds.push(reference.publicId);
      }
    }

    return {
      guardianPhotos,
      uploadedPublicIds,
      ...(studentPhoto ? { studentPhoto } : {}),
    };
  } catch (error) {
    await cleanupUploadedMedia(uploadedPublicIds);
    throw error;
  }
};

/**
 * Admission: process ordinary data, process optional media,
 * then combine both when creating the record.
 */

const createStudentService = async (
  input: StudentPayload,
  files: Express.Multer.File[] = [],
) => {
  const payload = { ...input } as Record<string, unknown>;

  // Extract subject selection before creating the student.
  const subjectSelection = payload.subjectSelection as
    | {
        configurationId: string;
        mainSubjectId?: string;
        mainSubjectIds?: string[];
        fourthSubjectId: string;
      }
    | undefined;

  delete payload.subjectSelection;

  // Media references must be generated by the server.
  delete payload.photo;

  // Prepare guardian data without accepting client-supplied photos.
  const guardians = Array.isArray(payload.guardians)
    ? (payload.guardians as GuardianPayload[]).map((guardian) => {
        const { photo: _untrustedPhoto, ...data } = guardian;
        return data;
      })
    : [];

  payload.guardians = guardians;

  const media = await processStudentMedia(files, guardians.length);

  const session = await mongoose.startSession();

  try {
    let createdStudent: InstanceType<typeof Student> | null = null;

    await session.withTransaction(async () => {
      const admissionDate = new Date(payload.admissionDate as string | Date);

      if (Number.isNaN(admissionDate.getTime())) {
        throw new AppError(400, "Invalid admission date.");
      }

      // --------------------------------------------------
      // SUBJECT SELECTION
      // --------------------------------------------------

      let resolvedSubjects: IStudentSubjectSelection[] = [];

      if (subjectSelection) {
        const {
          configurationId,
          mainSubjectId,
          mainSubjectIds,
          fourthSubjectId,
        } = subjectSelection;

        const isHumanities =
          ((payload.group as string) || "").trim().toUpperCase() ===
          "HUMANITIES";

        // Humanities requires three main subjects.
        // Science and Business Studies require one.
        const selectedMainSubjectIds = isHumanities
          ? (mainSubjectIds ?? [])
          : mainSubjectId
            ? [mainSubjectId]
            : [];

        // Validate selection IDs.
        if (
          !mongoose.isValidObjectId(configurationId) ||
          !mongoose.isValidObjectId(fourthSubjectId) ||
          selectedMainSubjectIds.length === 0 ||
          selectedMainSubjectIds.some((id) => !mongoose.isValidObjectId(id))
        ) {
          throw new AppError(400, "Invalid subject selection IDs.");
        }

        // Validate the required number of main subjects.
        const expectedMainSubjectCount = isHumanities ? 3 : 1;

        if (selectedMainSubjectIds.length !== expectedMainSubjectCount) {
          throw new AppError(
            400,
            isHumanities
              ? "Select exactly three main subjects from the Humanities clusters."
              : "Select exactly one main subject.",
          );
        }

        // Prevent duplicate main subjects.
        if (
          new Set(selectedMainSubjectIds).size !== selectedMainSubjectIds.length
        ) {
          throw new AppError(400, "Duplicate main subjects are not allowed.");
        }

        // Main and fourth subjects must be different.
        if (selectedMainSubjectIds.includes(fourthSubjectId)) {
          throw new AppError(
            400,
            "Main subject and fourth subject must be different.",
          );
        }

        const configuration = await SubjectConfiguration.findOne({
          _id: configurationId,
          isDeleted: false,
        }).session(session);

        if (!configuration) {
          throw new AppError(404, "Subject configuration not found.");
        }

        // Validate configuration against the new student's session/group.
        if (configuration.academicSession !== payload.academicSession) {
          throw new AppError(
            400,
            "Subject configuration does not match the academic session.",
          );
        }

        if (
          (configuration.group || "").trim().toUpperCase() !==
          ((payload.group as string) || "").trim().toUpperCase()
        ) {
          throw new AppError(
            400,
            "Subject configuration does not match the student's group.",
          );
        }

        // Find all selected main subjects in the configuration.
        const mainConfiguredSubjects = configuration.subjects.filter((item) =>
          selectedMainSubjectIds.includes(item.subject.toString()),
        );

        if (mainConfiguredSubjects.length !== selectedMainSubjectIds.length) {
          throw new AppError(
            400,
            "One or more selected main subjects are not in the configuration.",
          );
        }

        // Validate eligibility of every selected main subject.
        if (
          mainConfiguredSubjects.some((item) => !item.isMainSubjectEligible)
        ) {
          throw new AppError(
            400,
            "One or more selected main subjects are not eligible.",
          );
        }

        // Validate one subject from each Humanities cluster.
        if (isHumanities) {
          const requiredClusters = [
            "HUMANITIES_CLUSTER_1",
            "HUMANITIES_CLUSTER_2",
            "HUMANITIES_CLUSTER_3",
          ];

          for (const cluster of requiredClusters) {
            const selectedFromCluster = mainConfiguredSubjects.filter(
              (item) => item.selectionGroup === cluster,
            );

            if (selectedFromCluster.length !== 1) {
              throw new AppError(
                400,
                `Select exactly one subject from ${cluster}.`,
              );
            }
          }
        }

        // Find and validate the fourth subject.
        const fourthConfiguredSubject = configuration.subjects.find(
          (item) => item.subject.toString() === fourthSubjectId,
        );

        if (!fourthConfiguredSubject?.isFourthSubjectEligible) {
          throw new AppError(
            400,
            "The selected fourth subject is not eligible.",
          );
        }

        // Include compulsory, group-mandatory, required-selection,
        // selected main, and selected fourth subjects.
        const configuredSubjects = configuration.subjects.filter(
          (item) =>
            ["COMPULSORY", "GROUP_MANDATORY", "REQUIRED_SELECTION"].includes(
              item.subjectType,
            ) ||
            selectedMainSubjectIds.includes(item.subject.toString()) ||
            item.subject.toString() === fourthSubjectId,
        );

        // Remove duplicate subject IDs while preserving configuration order.
        const uniqueConfiguredSubjects = [
          ...new Map(
            configuredSubjects.map((item) => [item.subject.toString(), item]),
          ).values(),
        ];

        const subjectIds = uniqueConfiguredSubjects.map((item) => item.subject);

        // Fetch actual subject documents.
        const subjectDocuments = await Subject.find({
          _id: { $in: subjectIds },
          status: "active",
          isDeleted: false,
        }).session(session);

        if (subjectDocuments.length !== subjectIds.length) {
          throw new AppError(
            400,
            "One or more configured subjects are missing or inactive.",
          );
        }

        // Index subject documents by MongoDB IDs.
        const subjectMap = new Map(
          subjectDocuments.map((subject) => [subject._id.toString(), subject]),
        );

        // Build complete student subject-selection objects.
        resolvedSubjects = uniqueConfiguredSubjects.map((configuredSubject) => {
          const subjectId = configuredSubject.subject.toString();
          const subjectDocument = subjectMap.get(subjectId);

          if (!subjectDocument) {
            throw new AppError(
              400,
              "Configured subject could not be resolved.",
            );
          }

          const isMainSubject = selectedMainSubjectIds.includes(subjectId);

          const isFourthSubject = subjectId === fourthSubjectId;

          return {
            subject: subjectDocument._id,
            subjectName: subjectDocument.name,
            subjectCode: subjectDocument.code,
            isElective: isMainSubject || isFourthSubject,
            isFourthSubject,
          };
        });
      }

      // --------------------------------------------------
      // ACADEMIC HISTORY
      // --------------------------------------------------

      const academicHistoryEntry = {
        academicSession: payload.academicSession as string,
        className: payload.className as string,
        academicState: "current" as const,
        subjects: resolvedSubjects,
        ...(payload.group !== undefined
          ? { group: payload.group as string }
          : {}),
        ...(payload.section !== undefined
          ? { section: payload.section as string }
          : {}),
        ...(payload.rollNumber !== undefined
          ? { rollNumber: payload.rollNumber as string }
          : {}),
      };

      // --------------------------------------------------
      // PERSISTENCE PAYLOAD
      // --------------------------------------------------

      const persistencePayload: Record<string, unknown> = {
        ...payload,
        admissionDate,
        academicHistory: [academicHistoryEntry],
      };

      if (media.studentPhoto) {
        persistencePayload.photo = media.studentPhoto;
      }

      persistencePayload.guardians = guardians.map((guardian, index) => ({
        ...guardian,
        ...(media.guardianPhotos.has(index)
          ? { photo: media.guardianPhotos.get(index) }
          : {}),
      }));

      // --------------------------------------------------
      // CREATE STUDENT
      // --------------------------------------------------

      const studentId = await generateStudentId(admissionDate);

      const [student] = await Student.create(
        [
          {
            ...persistencePayload,
            studentId,
          },
        ],
        { session },
      );

      if (!student) {
        throw new AppError(500, "Failed to create student.");
      }

      createdStudent = student;
    });

    return createdStudent;
  } catch (error) {
    await cleanupUploadedMedia(media.uploadedPublicIds);
    throw error;
  } finally {
    await session.endSession();
  }
};

