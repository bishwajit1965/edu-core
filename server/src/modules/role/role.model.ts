import { Schema, model } from "mongoose";
import { IRole, RoleModel } from "./role.interface.js";

const roleSchema = new Schema<IRole, RoleModel>(
  {
    name: {
      type: String,
      required: true,
      trim: true,
    },
    key: {
      type: String,
      required: true,
      unique: true,
      uppercase: true,
      trim: true,
    },
    description: {
      type: String,
      trim: true,
      default: "",
    },
    isActive: {
      type: Boolean,
      default: true,
    },
    isDeleted: {
      type: Boolean,
      default: false,
    },
  },
  {
    timestamps: true,
  },
);

export const Role = model<IRole, RoleModel>("Role", roleSchema);
